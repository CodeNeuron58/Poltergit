import shutil
from pathlib import Path

from .git_history import Repository
from .web import ASSETS, TEMPLATES


def export_site(repo: Repository, output: Path, limit: int = 80) -> Path:
    output = output.resolve()
    marker = output / ".poltergit-export"
    if output.exists() and any(output.iterdir()) and not marker.is_file():
        raise ValueError("Choose an empty output directory. Existing files are never replaced unless this is a Poltergit export.")
    memorials = repo.memorials(limit)
    output.mkdir(parents=True, exist_ok=True)
    rendered = TEMPLATES.get_template("ofrenda.html").render(
        repo=repo.root.name, memorials=memorials, revision=repo.revision, limit=limit)
    (output / "index.html").write_text(rendered, encoding="utf-8")
    shutil.copyfile(ASSETS / "styles.css", output / "styles.css")
    (output / ".nojekyll").touch()
    marker.write_text("Generated by Poltergit. Safe to regenerate.\n", encoding="utf-8")
    return output
